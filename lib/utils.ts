/**
 * Normalize a player slug that looks like a variant (e.g. "martin-damm-D214")
 * by stripping trailing disambiguator segments. Returns the base slug or null
 * if no clear normalization candidate is found.
 */
export function normalizePlayerSlugVariant(slug?: string): string | null {
  if (!slug) return null;
  const s = String(slug).toLowerCase().trim();
  // Pattern: name-D123 (single letter followed by digits), common in some exports
  const m1 = s.match(/^(.+?)-[A-Za-z]\d+$/i);
  if (m1) return m1[1];
  // Pattern: name-XYZ or name-abc123 (short suffix up to 6 chars)
  const m2 = s.match(/^(.+?)-[A-Za-z0-9]{1,6}$/i);
  if (m2) return m2[1];
  return null;
}

/**
 * Build a canonical player href.
 * Prefer slug when available; fallback to ID (encoded) to preserve legacy links.
 * Accepts either an object with `{ slug, id }` or a plain id/slug string.
 */
export function getPlayerHref(input?: { id?: string | number | null; slug?: string | null } | string | null) {
  if (!input) return '#';
  if (typeof input === 'string') {
    // treat as slug preferably (may be numeric id as well)
    return `/players/${encodeURIComponent(String(input))}`;
  }
  const slug = (input && (input as any).slug) ? String((input as any).slug) : null;
  if (slug) return `/players/${encodeURIComponent(slug)}`;
  const id = (input && (input as any).id) ? String((input as any).id) : '';
  return id ? `/players/${encodeURIComponent(id)}` : '#';
}

// Build a player href optionally including a tab segment (e.g. '/players/:slug/matches').
// Keeps `getPlayerHref` behavior unchanged when `tab` is not provided.
export function getPlayerHrefWithTab(input?: { id?: string | number | null; slug?: string | null } | string | null, tab?: string | null) {
  const base = getPlayerHref(input);
  if (!tab) return base;
  // Avoid double slashes if base is '#'
  if (base === '#') return '#';
  return `${base}/${encodeURIComponent(tab)}`;
}

// Create a URL-friendly slug from text. Reused across the app.
export function createSlug(text?: string | null): string {
  if (!text) return '';
  const s = String(text || '');
  return s
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .trim()
    .replace(/^-|-$/g, '');
}

// Build a tournament href using available info. Prefer slug links (canonical), then fallback to ID.
export function getTourneyHref({ id, name, slug, year }: { id?: string | number | null; name?: any; slug?: string | null; year?: string | number | null }) {
  const y = year ? `/${year}` : '';
  // Prefer slug links when available (canonical URLs)
  if (slug) {
    return `/tournaments/${slug}${y}`;
  }

  // Fallback to ID links if slug not available
  if (id != null) {
    const sid = String(id);
    const parts = sid.split('-');
    if (parts.length === 2) {
      // legacy composite id like "2023-123" -> /tournaments/123/2023
      const yearPart = parts[0];
      const idPart = parts[1];
      return `/tournaments/${idPart}/${yearPart}`;
    }
    return `/tournaments/${sid}${y}`;
  }

  // Do NOT create slug from name; require slug or id to build canonical links
  return '#';
}


  // Parse dei set a partire dallo score del match.
  // Regole:
  // - Token tipo "6-4", "7-6(5)", "10-8" contano come set completi.
  // - Se lo score contiene "RET/ABD/DEF/W/O" e l'ultimo token è incompleto (es. "2-3"),
  ///   lo escludiamo.
  // - Per ogni set, 'a' è sempre il numero di game del vincitore del match (convenzione ATP).
  export function parseSetScores(score?: string | null) {
    if (!score) return [] as Array<{
        [x: string]: any; a: number; b: number; tb: boolean 
}>;
    const tokens = score.trim().split(/\s+/);
    const hasEarlyEnd = /\b(RET|ABD|DEF|W\/O|WO)\b/i.test(score);
    const sets: Array<{ a: number; b: number; tb: boolean }> = [];
  
    tokens.forEach((tok, idx) => {
      const m = tok.match(/^(\d+)\s*-\s*(\d+)(?:\s*\((\d+)\))?$/);
      if (!m) return;
      const a = parseInt(m[1], 10);
      const b = parseInt(m[2], 10);
      const hasTB = !!m[3];
      const max = Math.max(a, b);
      const diff = Math.abs(a - b);
  
      // Heuristica set completo
      let completed =
        hasTB || // tiebreak
        max >= 10 || // match tiebreak (es. 10-8)
        (max >= 6 && (diff >= 2 || max >= 7)); // 6-x con margine o 7-x
  
      // Se ultimo token e match finito in anticipo, scarta set palesemente incompleto
      if (!completed && hasEarlyEnd && idx === tokens.length - 1) return;
  
      sets.push({ a, b, tb: hasTB || max >= 10 });
    });
  
    return sets;
  }

