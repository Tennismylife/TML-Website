export function getFlagFromIOC(ioc?: string): string {
  if (!ioc) return "";
  const iso = IOC_TO_ISO[ioc.toUpperCase()];
  if (!iso) return ioc; // fallback: mostra IOC se non mappato
  return String.fromCodePoint(
    ...iso.toUpperCase().split("").map((c) => 127397 + c.charCodeAt(0))
  );
}

// Return Twemoji SVG URL for a flag given IOC code (or null if not available)
export function getFlagImgUrl(ioc?: string): string | null {
  if (!ioc) return null;
  const iso = IOC_TO_ISO[ioc.toUpperCase()];
  if (!iso) return null;
  const code = iso
    .toUpperCase()
    .split("")
    .map((c) => (127397 + c.charCodeAt(0)).toString(16))
    .join("-");
  return `https://twemoji.maxcdn.com/v/latest/svg/${code}.svg`;
}

export function getLevelFullName(level?: any) {
  // Support nested formats (string | string[] | object). Use first string found.
  const s = (typeof level === 'string') ? level : (Array.isArray(level) ? level[0] : (level && typeof level === 'object' ? Object.values(level)[0] : '')) || '';
  const l = String(s).toUpperCase().trim();

  // Known short codes
  switch (l) {
    case "G": return "Grand Slam";
    case "M": return "Masters 1000";
    case "A": return "Others";
    case "O": return "Olympics";
    case "D": return "Davis Cup";
    case "F": return "Finals";
  }

  // Numeric codes (e.g. "250", "500", "1000") or variants like "ATP 250"
  const digitsMatch = l.match(/(\d+)/);
  if (digitsMatch) {
    const n = digitsMatch[1];
    if (n === "1000") return "Masters 1000";
    return `ATP ${n}`;
  }

  // Other readable forms
  if (/GRAND SLAM|SLAM/.test(l)) return "Grand Slam";
  if (/FINALS/.test(l)) return "Finals";
  if (/MASTERS|1000/.test(l)) return "Masters 1000";
  if (/ATP/.test(l)) return l.replace(/\s+/g, " ");

  return s || "Unknown";
}

export function calculateAge(birthDate?: string | Date) {
  if (!birthDate) return "N/A";
  const birth = birthDate instanceof Date ? birthDate : new Date(birthDate);
  if (isNaN(birth.getTime())) return "N/A";
  const today = new Date();
  let ageYears = today.getFullYear() - birth.getFullYear();
  const monthDiff = today.getMonth() - birth.getMonth();
  if (monthDiff < 0 || (monthDiff === 0 && today.getDate() < birth.getDate())) {
    ageYears--;
  }
  // Giorni dopo l’ultimo compleanno
  const lastBirthday = new Date(today.getFullYear(), birth.getMonth(), birth.getDate());
  if (today < lastBirthday) {
    lastBirthday.setFullYear(today.getFullYear() - 1);
  }
  const daysDiff = Math.floor((today.getTime() - lastBirthday.getTime()) / (1000 * 60 * 60 * 24));
  const birthStr = birth.toISOString().split("T")[0]; // YYYY-MM-DD
  return `${ageYears}y ${daysDiff}d (${birthStr})`;
}


